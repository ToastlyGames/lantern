// Builds the static client into public/ and the shared game data the server validates against.
//   client-src/*.js + head/body html  →  public/index.html + public/game.js
//   client-src/data.js                →  lib/gamedata.js (same item/gear/skill tables on the server)
import { rmSync, readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { buildWiki } from './wiki.mjs';
const src = f => readFileSync(new URL('../client-src/' + f, import.meta.url), 'utf8');

// 1) shared data for the server
const data = src('data.js');
writeFileSync(new URL('../lib/gamedata.js', import.meta.url),
  '// GENERATED by scripts/build.mjs from client-src/data.js. Do not edit; edit client-src/data.js and run npm run build.\n' + data +
  '\nexport { ITEMS, GEAR, HELM_ATTR, RARITY, RORDER, LANTERNS, CAPES, ATTR_TXT, SKILLS, XP_TABLE, levelFor, combatFrom, FISH, WATERS, CROPS, RECIPES, SHOP, PLOT_BASE, PLOT_MAX, PLOT_LVLS, PLOT_BUYS, plotCap, cleanPlots, ENEMIES, PACKS, NAMES };\n');

// 2) client: one script file (so the page can use a strict Content-Security-Policy), styles inline
const js = ['font.js', 'art.js', 'data.js', 'changelog.js', 'world.js', 'net.js', 'game.js', 'account-live.js'].map(src).join('\n');
const hash = createHash('sha256').update(js).digest('hex').slice(0, 10);
mkdirSync(new URL('../public/', import.meta.url), { recursive: true });
writeFileSync(new URL('../public/game.js', import.meta.url), js);
const head = src('head.html').replace('/*FONTFACE*/', src('fontface.css'));
writeFileSync(new URL('../public/index.html', import.meta.url), head + src('body.html') + `<script src="/game.js?v=${hash}"></script></body></html>`);
// 3) favicons and the home-screen manifest
for (const f of readdirSync(new URL('../client-src/icons/', import.meta.url))) copyFileSync(new URL('../client-src/icons/' + f, import.meta.url), new URL('../public/' + f, import.meta.url));
// 4) CHANGELOG.md, from the same list the in-game Bulletin shows
{ const { BUILD, CHANGELOG } = new Function(src('changelog.js') + '\nreturn { BUILD, CHANGELOG };')();
  const md = `# Lanternhold changelog\n\nCurrent build: **v${BUILD.version}** · ${BUILD.season}\n\n` + CHANGELOG.map(e => `## v${e.v} · ${e.title}\n\n_${e.date}_\n\n` + e.notes.map(n => '- ' + n).join('\n')).join('\n\n') + '\n';
  writeFileSync(new URL('../CHANGELOG.md', import.meta.url), md);
  writeFileSync(new URL('../lib/build.js', import.meta.url), '// GENERATED by scripts/build.mjs from client-src/changelog.js (do not edit).\nexport const BUILD = ' + JSON.stringify(BUILD) + ';\n'); }
// 5) the owner tools (/tools: rewards vault, Founder's Lantern, ...), locked to the admin wallets (lib/admins.js).
// They are NOT written to public/ (anything there is public): they're bundled into lib/toolfiles.js and only served by
// api/tools.js to a signed-in admin wallet. Any file added to client-src/tools/ is locked the same way.
rmSync(new URL('../public/tools/', import.meta.url), { recursive: true, force: true });
{ const byte = f => JSON.parse(readFileSync(new URL('../contracts/' + f, import.meta.url), 'utf8')).bytecode;
  const files = {};
  for (const f of readdirSync(new URL('../client-src/tools/', import.meta.url))) files[f] = src('tools/' + f);
  files['vault.js'] = files['vault.js'].replace('__BYTECODE__', byte('LanternRewards.json'));
  files['founders.js'] = files['founders.js'].replace('__BYTECODE__', byte('LanternFounders.json'));
  writeFileSync(new URL('../lib/toolfiles.js', import.meta.url), '// GENERATED by scripts/build.mjs from client-src/tools/ (do not edit). Served only by api/tools.js.\nexport const TOOL_FILES = ' + JSON.stringify(files) + ';\n'); }
// 5) the public wiki at /wiki, from docs/WIKI.md + the update history
buildWiki();
console.log('built public/index.html, public/game.js (' + (js.length / 1024).toFixed(0) + ' KB), lib/gamedata.js, public/wiki/');
